package com.example.data.repository

import com.example.data.local.SecurityDao
import com.example.data.model.AccessLogEntity
import com.example.data.model.ActionType
import com.example.data.model.AutomationLogEntity
import com.example.data.model.AutomationRuleEntity
import com.example.data.model.CheckpointEntity
import com.example.data.model.GateClearanceStatus
import com.example.data.model.IncidentEntity
import com.example.data.model.IncidentPriority
import com.example.data.model.IncidentStatus
import com.example.data.model.IncidentType
import com.example.data.model.TriggerType
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.first

class SecurityRepository(private val dao: SecurityDao) {

  // Rules
  fun getAllRules(): Flow<List<AutomationRuleEntity>> = dao.getAllRulesFlow()

  suspend fun toggleRule(ruleId: Long, isEnabled: Boolean) {
    dao.setRuleEnabled(ruleId, isEnabled)
  }

  suspend fun createRule(rule: AutomationRuleEntity): Long {
    val id = dao.insertRule(rule)
    dao.insertAutomationLog(
      AutomationLogEntity(
        ruleTitle = rule.title,
        triggerDesc = "New Rule Provisioned",
        actionExecuted = "Action: ${rule.actionType.displayName}",
        details = "Sector: ${rule.sector}"
      )
    )
    return id
  }

  suspend fun deleteRule(rule: AutomationRuleEntity) {
    dao.deleteRule(rule)
  }

  suspend fun simulateTriggerRule(rule: AutomationRuleEntity) {
    val now = System.currentTimeMillis()
    dao.recordRuleExecution(rule.id, now)
    dao.insertAutomationLog(
      AutomationLogEntity(
        ruleTitle = rule.title,
        triggerDesc = "Triggered: ${rule.triggerType.displayName}",
        actionExecuted = "Executed: ${rule.actionType.displayName}",
        status = "EXECUTED",
        details = "Sector: ${rule.sector} | ${rule.conditionDesc}"
      )
    )

    // If rule action is auto dispatch or lockdown or alarm, also create an incident automatically
    if (rule.actionType == ActionType.AUTO_DISPATCH || rule.actionType == ActionType.LOCKDOWN_GATE || rule.actionType == ActionType.SOUND_ALARM) {
      val incident = IncidentEntity(
        title = "Automated SecOps Trigger: ${rule.title}",
        type = when (rule.triggerType) {
          TriggerType.SENSOR -> IncidentType.INTRUSION
          TriggerType.BADGE -> IncidentType.ACCESS_VIOLATION
          TriggerType.LONE_WORKER_INACTIVITY -> IncidentType.MEDICAL
          TriggerType.CHECKPOINT_DELAY -> IncidentType.SUSPICIOUS
          else -> IncidentType.HAZARD
        },
        priority = IncidentPriority.CRITICAL,
        status = IncidentStatus.OPEN,
        reportedAtEpochMs = now,
        location = rule.sector,
        notes = "Auto-generated by automation rule #${rule.id} (${rule.title}) upon condition match: ${rule.conditionDesc}",
        sopStepsRaw = "Acknowledge Central Dispatch|Dispatch patrol unit to ${rule.sector}|Verify perimeter sensors|Resolve alarm condition|Submit automated incident summary",
        completedStepsCount = 0
      )
      dao.insertIncident(incident)
    }
  }

  // Checkpoints
  fun getAllCheckpoints(): Flow<List<CheckpointEntity>> = dao.getAllCheckpointsFlow()

  suspend fun completeCheckpoint(id: Long, notes: String) {
    val now = System.currentTimeMillis()
    dao.completeCheckpoint(id, now, notes)
    dao.insertAutomationLog(
      AutomationLogEntity(
        ruleTitle = "Automated Patrol Pacing",
        triggerDesc = "Checkpoint Verified",
        actionExecuted = "Timestamp logged & pace verified",
        details = "Checkpoint ID #$id marked complete"
      )
    )
  }

  suspend fun resetRouteCheckpoints() {
    dao.resetRouteCheckpoints()
    dao.insertAutomationLog(
      AutomationLogEntity(
        ruleTitle = "Patrol Cycle Reset",
        triggerDesc = "New Shift Initiated",
        actionExecuted = "All checkpoints reset to pending status",
        details = "Officer reset round"
      )
    )
  }

  // Incidents
  fun getAllIncidents(): Flow<List<IncidentEntity>> = dao.getAllIncidentsFlow()

  suspend fun reportIncident(
    title: String,
    type: IncidentType,
    priority: IncidentPriority,
    location: String,
    notes: String,
    sopSteps: String
  ): Long {
    val incident = IncidentEntity(
      title = title,
      type = type,
      priority = priority,
      status = IncidentStatus.OPEN,
      location = location,
      notes = notes,
      sopStepsRaw = sopSteps,
      completedStepsCount = 0
    )
    val id = dao.insertIncident(incident)
    dao.insertAutomationLog(
      AutomationLogEntity(
        ruleTitle = "Incident Auto-Dispatch",
        triggerDesc = "Priority ${priority.tag} ${type.title}",
        actionExecuted = "Incident #$id logged. Central dispatcher alert broadcast.",
        details = "Location: $location"
      )
    )
    return id
  }

  suspend fun updateIncidentStatus(id: Long, status: IncidentStatus) {
    dao.updateIncidentStatus(id, status)
  }

  suspend fun updateIncident(incident: IncidentEntity) {
    dao.updateIncident(incident)
  }

  // Access Control
  fun getRecentAccessLogs(): Flow<List<AccessLogEntity>> = dao.getRecentAccessLogsFlow()

  suspend fun recordAccessDecision(
    badgeId: String,
    visitorName: String,
    company: String,
    clearanceLevel: String,
    vehiclePlate: String,
    gateName: String,
    status: GateClearanceStatus,
    reason: String
  ) {
    dao.insertAccessLog(
      AccessLogEntity(
        badgeId = badgeId,
        visitorName = visitorName,
        company = company,
        clearanceLevel = clearanceLevel,
        vehiclePlate = vehiclePlate,
        gateName = gateName,
        status = status,
        automatedReason = reason
      )
    )
    dao.insertAutomationLog(
      AutomationLogEntity(
        ruleTitle = "Gate Automation Engine",
        triggerDesc = "Clearance Evaluation for $badgeId",
        actionExecuted = "Gate barrier: ${status.name}",
        details = "Gate: $gateName | Plate: $vehiclePlate"
      )
    )
  }

  // Automation Logs
  fun getRecentAutomationLogs(): Flow<List<AutomationLogEntity>> = dao.getRecentAutomationLogsFlow()

  suspend fun logAutomationEvent(title: String, trigger: String, action: String, details: String) {
    dao.insertAutomationLog(
      AutomationLogEntity(
        ruleTitle = title,
        triggerDesc = trigger,
        actionExecuted = action,
        details = details
      )
    )
  }

  suspend fun seedIfEmpty() {
    val existing = dao.getAllRulesFlow().first()
    if (existing.isEmpty()) {
      // Direct call fallback
    }
  }
}
